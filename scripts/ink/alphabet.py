def glyph(ch: str) -> Glyph | None:
    if ch == " ":
        return None
    g = GLYPHS.get(ch.upper())
    if g:
        return g
    return GLYPHS.get(ch)


def map_stroke(st: Stroke, origin: V, w: float, h: float) -> list[V]:
    raw = pts(*st.xy)
    return [V(origin.x + p.x * w, origin.y + p.y * h) for p in raw]
