from __future__ import annotations

from dataclasses import dataclass

from .geom import V, pts


@dataclass(frozen=True)
class Stroke:
    xy: tuple[float, ...]
    root: float = 0.16
    tip: float = 0.045
    amp: float = 0.012
    freq: float = 1.7
    side: int = 1
    closed: bool = False


@dataclass(frozen=True)
class Glyph:
    width: float
    strokes: tuple[Stroke, ...]


def S(*xy: float, root: float = 0.16, tip: float = 0.045, amp: float = 0.012, freq: float = 1.7, side: int = 1, closed: bool = False) -> Stroke:
    return Stroke(xy, root, tip, amp, freq, side, closed)


